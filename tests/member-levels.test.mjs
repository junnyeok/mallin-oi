import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {PGlite}=await import(process.env.PGLITE_MODULE_PATH || '@electric-sql/pglite');
const sql=await readFile('supabase/migrations/20261117020000_member_levels.sql','utf8');
test('XP backfill, live awards, boundaries, deduplication, permissions and visitor ranking',async()=>{
 const db=new PGlite();
 const a='00000000-0000-4000-8000-000000000001',b='00000000-0000-4000-8000-000000000002';
 try{
 await db.exec(`create schema auth; create role anon; create role authenticated;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create table auth.users(id uuid primary key);
 insert into auth.users values('${a}'),('${b}');
 create table public_profiles(id uuid primary key,nickname text,profile_image_url text,equipped_character_image_url text,equipped_character_effect_item_id text,equipped_profile_background_item_id text,equipped_profile_frame_item_id text);
 insert into public_profiles(id,nickname) values('${a}','Z'),('${b}','A');
 create table posts(id bigint primary key,author_id uuid,created_at timestamptz default now());
 create table post_comments(id bigint primary key,author_id uuid,parent_comment_id bigint,created_at timestamptz default now());
 create table post_reactions(id bigint primary key,post_id bigint,user_id uuid,reaction_type text,created_at timestamptz default now());
 create table pickle_ledger(user_id uuid,reason_code text,amount integer,awarded_on date,created_at timestamptz default now());
 create table site_daily_visits(user_id uuid,guest_id uuid,visitor_key text,visit_date date);
 insert into posts values(1,'${a}',now());
 insert into post_comments values(1,'${a}',null,now()),(2,'${a}',1,now());
 insert into post_reactions values(1,1,'${b}','like',now()),(2,1,'${a}','like',now());
 insert into pickle_ledger values('${a}','attendance',10,current_date,now()),('${a}','attendance',10,current_date,now());
 insert into site_daily_visits(user_id,visit_date) values('${a}',(now() at time zone 'Asia/Seoul')::date),('${b}',(now() at time zone 'Asia/Seoul')::date);
 `);
 await db.exec(sql);
 const stats=async id=>(await db.query('select total_xp,level,level_xp,next_level_xp from public_member_levels where id=$1',[id])).rows[0];
 assert.deepEqual(await stats(a),{total_xp:43,level:1,level_xp:43,next_level_xp:100});
 assert.equal((await stats(b)).total_xp,2);
 await db.exec(sql);assert.equal((await stats(a)).total_xp,43);
 await db.exec(`delete from post_reactions where id=1; insert into post_reactions values(3,1,'${b}','dislike',now());`);
 assert.equal((await stats(a)).total_xp,43);assert.equal((await stats(b)).total_xp,2);
 await db.exec(`insert into posts values(2,'${a}',now()); insert into post_comments values(3,'${a}',2,now()); insert into pickle_ledger values('${a}','attendance',10,current_date+1,now());`);
 assert.equal((await stats(a)).total_xp,78);
 await db.exec(`insert into member_xp_events values('${a}','post','boundary',21,now());`);
 assert.deepEqual(await stats(a),{total_xp:99,level:1,level_xp:99,next_level_xp:100});
 await db.exec(`update member_xp_events set xp=22 where source_key='boundary';`);
 assert.deepEqual(await stats(a),{total_xp:100,level:2,level_xp:0,next_level_xp:200});
 await db.exec(`update member_xp_events set xp=222 where source_key='boundary';`);
 assert.deepEqual(await stats(a),{total_xp:300,level:3,level_xp:0,next_level_xp:300});
 await db.exec(`set role anon`);
 assert.equal((await db.query('select id from public_member_levels order by total_xp desc')).rows[0].id,a);
 await assert.rejects(db.query('select * from member_xp_events'),/permission denied/);
 await assert.rejects(db.query(`insert into member_xp_events values('${b}','post','hack',999,now())`),/permission denied/);
 await assert.rejects(db.query('select get_today_site_people()'),/permission denied/);
 await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${b}',false);`);
 const today=(await db.query('select get_today_site_people() as result')).rows[0].result;
 assert.equal(today.items[0].user_id,a);assert.equal(today.items[0].level,3);
 await assert.rejects(db.query(`update member_xp_events set xp=999`),/permission denied/);
 assert.equal(sql,await readFile('supabase-SQLEditor/20261117-member-levels.sql','utf8'));
 }finally{await db.close();}
});
