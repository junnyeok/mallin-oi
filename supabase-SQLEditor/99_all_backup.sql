-- 반응 요약 조회 RPC
-- anon도 숫자는 볼 수 있게
-- =========================================
create or replace function public.get_post_reaction_summary(
  p_post_id bigint,
  p_user_id uuid default null
)
returns table (
  likes_count bigint,
  dislikes_count bigint,
  my_reaction text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_likes_count bigint := 0;
  v_dislikes_count bigint := 0;
  v_my_reaction text := null;
begin
  select
    count(*) filter (where reaction_type = 'like'),
    count(*) filter (where reaction_type = 'dislike')
  into v_likes_count, v_dislikes_count
  from public.post_reactions
  where post_id = p_post_id;

  if p_user_id is not null then
    select reaction_type
    into v_my_reaction
    from public.post_reactions
    where post_id = p_post_id
      and user_id = p_user_id
    limit 1;
  end if;

  return query
  select
    coalesce(v_likes_count, 0),
    coalesce(v_dislikes_count, 0),
    v_my_reaction;
end;
$$;

grant execute on function public.get_post_reaction_summary(bigint, uuid) to anon, authenticated;

-- =========================================
-- 반응 토글 RPC
-- - 같은 반응 다시 누르면 삭제
-- - 다른 반응 누르면 변경
-- =========================================
create or replace function public.toggle_post_reaction(
  p_post_id bigint,
  p_reaction_type text
)
returns table (
  likes_count bigint,
  dislikes_count bigint,
  my_reaction text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid;
  v_existing_reaction text;
  v_safe_reaction text;
begin
  v_user_id := auth.uid();

  if v_user_id is null then
    raise exception 'LOGIN_REQUIRED';
  end if;

  v_safe_reaction := lower(trim(coalesce(p_reaction_type, '')));

  if v_safe_reaction not in ('like', 'dislike') then
    raise exception 'INVALID_REACTION_TYPE';
  end if;

  select reaction_type
  into v_existing_reaction
  from public.post_reactions
  where post_id = p_post_id
    and user_id = v_user_id
  limit 1;

  if v_existing_reaction is null then
    insert into public.post_reactions (
      post_id,
      user_id,
      reaction_type
    )
    values (
      p_post_id,
      v_user_id,
      v_safe_reaction
    );

  elsif v_existing_reaction = v_safe_reaction then
    delete from public.post_reactions
    where post_id = p_post_id
      and user_id = v_user_id;

  else
    update public.post_reactions
    set reaction_type = v_safe_reaction
    where post_id = p_post_id
      and user_id = v_user_id;
  end if;

  return query
  select *
  from public.get_post_reaction_summary(p_post_id, v_user_id);
end;
$$;

grant execute on function public.toggle_post_reaction(bigint, text) to authenticated;

