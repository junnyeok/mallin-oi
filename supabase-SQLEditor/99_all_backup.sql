create or replace function public.mask_email(p_email text)
returns text
language plpgsql
immutable
as $$
declare
  v_email text := coalesce(trim(p_email), '');
  v_local text;
  v_domain text;
  v_domain_name text;
  v_tld text;
begin
  if v_email = '' or position('@' in v_email) = 0 then
    return '';
  end if;

  v_local := split_part(v_email, '@', 1);
  v_domain := split_part(v_email, '@', 2);
  v_domain_name := split_part(v_domain, '.', 1);
  v_tld := regexp_replace(v_domain, '^[^.]+\.', '');

  if char_length(v_local) <= 1 then
    v_local := '*';
  else
    v_local := left(v_local, 1) || repeat('*', greatest(char_length(v_local) - 1, 1));
