begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'posts_private_password_check'
  ) then
    alter table public.posts
    add constraint posts_private_password_check
    check (
      (is_private = false and secret_password_hash is null)
      or
      (is_private = true and secret_password_hash is not null and btrim(secret_password_hash) <> '')
    );
  end if;
end $$;

