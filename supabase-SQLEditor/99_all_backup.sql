    -- 하루 최대 10개 댓글/답글까지만 지급
    select count(*)
      into v_daily_count
    from public.pickle_ledger
    where user_id = p_user_id
      and reason_code = 'comment_post'
      and awarded_on = v_awarded_on;

    if v_daily_count >= 10 then
      return false;
    end if;

  else
    return false;
  end if;

  if v_exists then
    return false;
  end if;

  insert into public.pickle_ledger (
    user_id,
    amount,
    reason_code,
    reason_label,
    description,
    source_post_id,
    source_comment_id,
    awarded_on
  )
  values (
    p_user_id,
    p_amount,
    p_reason_code,
    coalesce(nullif(trim(p_reason_label), ''), '피클 획득'),
    coalesce(p_description, ''),
    p_source_post_id,
    p_source_comment_id,
    v_awarded_on
  );

  update public.profiles
  set pickles = coalesce(pickles, 0) + p_amount,
      updated_at = now()
  where id = p_user_id;

  return true;
end;
$$;

