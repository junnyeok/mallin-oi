-- =========================================
-- auth.users -> public.profiles 동기화 함수
-- 회원가입 / 사용자정보 수정 시 자동 반영
-- =========================================

create or replace function public.sync_profile_from_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_nickname text;
begin
  v_nickname := nullif(trim(coalesce(new.raw_user_meta_data->>'nickname', '')), '');

  if v_nickname is null then
    v_nickname := split_part(coalesce(new.email, ''), '@', 1);
  end if;

  insert into public.profiles (id, email, nickname, created_at, updated_at)
  values (new.id, coalesce(new.email, ''), v_nickname, now(), now())
  on conflict (id)
  do update set
    email = excluded.email,
    nickname = excluded.nickname,
    updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_sync_profile on auth.users;
create trigger on_auth_user_created_sync_profile
after insert on auth.users
for each row
execute function public.sync_profile_from_auth_user();

drop trigger if exists on_auth_user_updated_sync_profile on auth.users;
create trigger on_auth_user_updated_sync_profile
after update of email, raw_user_meta_data on auth.users
for each row
execute function public.sync_profile_from_auth_user();

-- =========================================
-- 가입 가능 여부 확인용 RPC
-- anon도 호출 가능하게 security definer 사용
-- exclude_user_id는 마이페이지 닉네임 변경 때 사용
-- =========================================

create or replace function public.check_account_availability(
  p_email text default null,
  p_nickname text default null,
  p_exclude_user_id uuid default null
)
returns table (
  email_exists boolean,
  nickname_exists boolean
)
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  select
    exists (
      select 1
      from public.profiles
      where p_email is not null
        and lower(email) = lower(trim(p_email))
        and (p_exclude_user_id is null or id <> p_exclude_user_id)
    ) as email_exists,
    exists (
      select 1
      from public.profiles
      where p_nickname is not null
        and lower(nickname) = lower(trim(p_nickname))
        and (p_exclude_user_id is null or id <> p_exclude_user_id)
    ) as nickname_exists;
end;
$$;

grant execute on function public.check_account_availability(text, text, uuid)
to anon, authenticated;

-- =========================================
-- 기존 auth.users 데이터를 profiles로 한 번 밀어넣기
-- 이미 있으면 업데이트
-- =========================================

insert into public.profiles (id, email, nickname, created_at, updated_at)
select
  u.id,
  coalesce(u.email, ''),
  coalesce(nullif(trim(u.raw_user_meta_data->>'nickname'), ''), split_part(coalesce(u.email, ''), '@', 1)),
  now(),
  now()
from auth.users u
on conflict (id)
do update set
  email = excluded.email,
  nickname = excluded.nickname,
  updated_at = now();

  -- =========================================
-- 닉네임 변경 시 기존 게시물 / 댓글 작성자명 자동 동기화
-- =========================================

create or replace function public.sync_author_nickname_from_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- nickname이 비어 있으면 아무 것도 하지 않음
  if new.nickname is null or btrim(new.nickname) = '' then
    return new;
  end if;

  -- 닉네임이 실제로 바뀐 경우에만 실행
  if tg_op = 'UPDATE' and coalesce(old.nickname, '') = coalesce(new.nickname, '') then
    return new;
  end if;

  -- 기존 게시물 작성자명 일괄 변경
  update public.posts
  set
    author_nickname = new.nickname,
    updated_at = now()
  where author_id = new.id;

  -- 기존 댓글 작성자명 일괄 변경
  update public.post_comments
  set author_nickname = new.nickname
  where author_id = new.id;

  return new;
end;
$$;

drop trigger if exists trg_profiles_sync_author_nickname on public.profiles;

create trigger trg_profiles_sync_author_nickname
after update of nickname on public.profiles
for each row
execute function public.sync_author_nickname_from_profile();

