  v_birth text := nullif(public.normalize_birth_key(p_birth_key), '');
  v_question text := nullif(trim(coalesce(p_recovery_question, '')), '');
  v_answer_hash text := nullif(trim(coalesce(p_recovery_answer_hash, '')), '');
  v_count integer := 0;
