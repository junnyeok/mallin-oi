-- 부모 댓글 검증 함수
create or replace function public.validate_post_comment_parent()
returns trigger
language plpgsql
as $$
declare
  v_parent_post_id bigint;
  v_parent_parent_id bigint;
begin
  -- 일반 댓글이면 통과
  if new.parent_comment_id is null then
    return new;
  end if;

  -- 부모 댓글 조회
  select post_id, parent_comment_id
    into v_parent_post_id, v_parent_parent_id
  from public.post_comments
  where id = new.parent_comment_id;

  -- 부모 댓글이 없으면 에러
  if v_parent_post_id is null then
    raise exception '부모 댓글을 찾을 수 없어.';
  end if;

  -- 같은 게시글 안에서만 답글 허용
  if v_parent_post_id <> new.post_id then
    raise exception '다른 게시글의 댓글에는 답글을 달 수 없어.';
  end if;

  -- 답글의 답글 금지 (1단계까지만)
  if v_parent_parent_id is not null then
    raise exception '답글에는 다시 답글을 달 수 없어.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_validate_post_comment_parent on public.post_comments;
create trigger trg_validate_post_comment_parent
before insert or update on public.post_comments
for each row
execute function public.validate_post_comment_parent();

