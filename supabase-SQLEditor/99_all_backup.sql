  p_real_name text,
  p_birth_key text
)
returns table (
  found boolean,
  ambiguous boolean,
  masked_email text,
  recovery_question text,
  recovery_question_label text
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := nullif(trim(coalesce(p_real_name, '')), '');
  v_birth text := nullif(public.normalize_birth_key(p_birth_key), '');
