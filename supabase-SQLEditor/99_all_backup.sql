-- "진짜 수정"일 때만 updated_at 변경
-- - posts: title, excerpt, body, category, tags, pinned, media_items 변경 시만
-- - post_comments: body 관련 내용 변경 시만
-- 조회수 증가, 작성자명 동기화 같은 update는 updated_at 유지
-- =========================================================

-- -----------------------------------------
-- 1. posts 전용 updated_at 함수
-- -----------------------------------------
create or replace function public.handle_posts_updated_at_only_on_real_edit()
returns trigger
language plpgsql
as $$
begin
  if
    new.title        is distinct from old.title
    or new.excerpt   is distinct from old.excerpt
    or new.body      is distinct from old.body
    or new.category  is distinct from old.category
    or new.tags      is distinct from old.tags
    or new.pinned    is distinct from old.pinned
    or new.media_items is distinct from old.media_items
  then
    new.updated_at := now();
  else
    new.updated_at := old.updated_at;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_posts_updated_at on public.posts;
create trigger trg_posts_updated_at
before update on public.posts
for each row
execute function public.handle_posts_updated_at_only_on_real_edit();

-- -----------------------------------------
-- 2. post_comments 전용 updated_at 함수
-- -----------------------------------------
create or replace function public.handle_post_comments_updated_at_only_on_real_edit()
returns trigger
language plpgsql
as $$
begin
  if
    new.body is distinct from old.body
    or new.parent_comment_id is distinct from old.parent_comment_id
    or new.reply_to_comment_id is distinct from old.reply_to_comment_id
    or new.reply_to_nickname is distinct from old.reply_to_nickname
  then
    new.updated_at := now();
  else
    new.updated_at := old.updated_at;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_post_comments_updated_at on public.post_comments;
create trigger trg_post_comments_updated_at
before update on public.post_comments
for each row
execute function public.handle_post_comments_updated_at_only_on_real_edit();

-- -----------------------------------------
-- 3. updated_at가 없던 경우만 보정
-- 이미 잘못 덮인 "과거 수정시간"은 원래값 복구 불가
-- 별도 이력/백업이 없으면 정확 복원은 못함
-- -----------------------------------------
update public.posts
set updated_at = coalesce(updated_at, created_at, now())
where updated_at is null;

update public.post_comments
set updated_at = coalesce(updated_at, created_at, now())
where updated_at is null;

