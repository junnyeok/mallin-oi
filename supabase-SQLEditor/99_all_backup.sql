-- =========================================================
-- 3. posts에서 pinned를 일반유저가 못 건드리게 막는 트리거 함수
--    - insert 시 일반유저가 pinned=true 넣으면 에러
--    - update 시 일반유저가 pinned 값 바꾸면 에러
-- =========================================================
create or replace function public.guard_posts_pinned_admin_only()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- 로그인 사용자 기준
  if public.is_admin_user(auth.uid()) then
    return new;
  end if;

  -- 일반 유저는 insert 시 pinned=true 금지
  if tg_op = 'INSERT' then
    if coalesce(new.pinned, false) = true then
      raise exception 'pinned는 관리자만 설정할 수 있어.';
    end if;

    return new;
  end if;

  -- 일반 유저는 update 시 pinned 값 변경 금지
  if tg_op = 'UPDATE' then
    if coalesce(new.pinned, false) <> coalesce(old.pinned, false) then
      raise exception 'pinned 변경은 관리자만 할 수 있어.';
    end if;

    return new;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_posts_pinned_admin_only on public.posts;

create trigger trg_guard_posts_pinned_admin_only
before insert or update on public.posts
for each row
execute function public.guard_posts_pinned_admin_only();

