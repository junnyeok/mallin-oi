-- 5. 상세 조회 RPC
--    - 공개글: 바로 본문 반환
--    - 비밀글: 작성자/관리자 or 비밀번호 일치 시 본문 반환
--    - 잠긴 상태면 본문/body, media_items 반환 안 함
-- ---------------------------------------------------------
create or replace function public.get_post_detail(
  p_post_id bigint,
  p_secret_password text default null
)
returns table (
  id bigint,
  title text,
  excerpt text,
  body text,
  category text,
  tags text[],
  pinned boolean,
  views integer,
  media_items jsonb,
  author_id uuid,
  author_nickname text,
  created_at timestamptz,
  updated_at timestamptz,
  is_private boolean,
  is_unlocked boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_is_admin boolean := public.is_admin_user(v_uid);
  v_post public.posts%rowtype;
  v_is_owner boolean := false;
  v_pw_ok boolean := false;
begin
  select *
    into v_post
  from public.posts
  where posts.id = p_post_id;

  if not found then
    return;
  end if;

  v_is_owner := (v_uid is not null and v_post.author_id = v_uid);

  if v_post.is_private = false then
    return query
    select
      v_post.id,
      v_post.title,
      v_post.excerpt,
      v_post.body,
      v_post.category,
      v_post.tags,
      v_post.pinned,
      v_post.views,
      v_post.media_items,
      v_post.author_id,
      v_post.author_nickname,
      v_post.created_at,
      v_post.updated_at,
      v_post.is_private,
      true;
    return;
  end if;

  if v_is_owner or v_is_admin then
    return query
    select
      v_post.id,
      v_post.title,
      v_post.excerpt,
      v_post.body,
      v_post.category,
      v_post.tags,
      v_post.pinned,
      v_post.views,
      v_post.media_items,
      v_post.author_id,
      v_post.author_nickname,
      v_post.created_at,
      v_post.updated_at,
      v_post.is_private,
      true;
    return;
  end if;

  if nullif(public.normalize_secret_password(p_secret_password), '') is not null then
    v_pw_ok := (
      public.sha256_hex(public.normalize_secret_password(p_secret_password))
      = coalesce(v_post.secret_password_hash, '')
    );
  end if;

  if v_pw_ok then
    return query
    select
      v_post.id,
      v_post.title,
      v_post.excerpt,
      v_post.body,
      v_post.category,
      v_post.tags,
      v_post.pinned,
      v_post.views,
      v_post.media_items,
      v_post.author_id,
      v_post.author_nickname,
      v_post.created_at,
      v_post.updated_at,
      v_post.is_private,
      true;
    return;
  end if;

  -- 잠긴 상태
  return query
  select
    v_post.id,
    v_post.title,
    v_post.excerpt,
    null::text as body,
    v_post.category,
    v_post.tags,
    v_post.pinned,
    v_post.views,
    '[]'::jsonb as media_items,
    v_post.author_id,
    v_post.author_nickname,
    v_post.created_at,
    v_post.updated_at,
    v_post.is_private,
    false;
end;
$$;

grant execute on function public.get_post_detail(bigint, text) to anon, authenticated;

