-- =========================================================
-- 검증 함수
-- - 일반 댓글: parent_comment_id null
-- - 답글: parent_comment_id는 반드시 "루트 댓글" id
-- - reply_to_comment_id는 같은 post 안의 댓글이어야 함
-- - reply_to_comment_id가 루트 또는 그 루트의 답글이어야 함
-- =========================================================

create or replace function public.validate_post_comment_thread()
returns trigger
language plpgsql
as $$
declare
  v_root_id bigint;
  v_root_post_id bigint;
  v_root_parent_id bigint;

  v_target_id bigint;
  v_target_post_id bigint;
  v_target_parent_id bigint;
  v_target_author_nickname text;
begin
  -- 일반 댓글
  if new.parent_comment_id is null then
    new.reply_to_comment_id := null;
    new.reply_to_nickname := null;
    return new;
  end if;

  -- 루트 댓글 검증
  select id, post_id, parent_comment_id
    into v_root_id, v_root_post_id, v_root_parent_id
  from public.post_comments
  where id = new.parent_comment_id;

  if v_root_id is null then
    raise exception '루트 댓글을 찾을 수 없어.';
  end if;

  if v_root_post_id <> new.post_id then
    raise exception '다른 게시글의 댓글 스레드에는 답글을 달 수 없어.';
  end if;

  -- parent_comment_id는 반드시 최상위 댓글이어야 함
  if v_root_parent_id is not null then
    raise exception 'parent_comment_id는 최상위 댓글이어야 해.';
  end if;

  -- reply_to_comment_id가 비어 있으면 루트 댓글에 답글 단 것으로 처리
  if new.reply_to_comment_id is null then
    new.reply_to_comment_id := new.parent_comment_id;
  end if;

  -- 실제 답글 대상 검증
  select id, post_id, parent_comment_id, author_nickname
    into v_target_id, v_target_post_id, v_target_parent_id, v_target_author_nickname
  from public.post_comments
  where id = new.reply_to_comment_id;

  if v_target_id is null then
    raise exception '답글 대상 댓글을 찾을 수 없어.';
  end if;

  if v_target_post_id <> new.post_id then
    raise exception '다른 게시글의 댓글에는 답글을 달 수 없어.';
  end if;

  -- 답글 대상은 같은 루트 스레드 안에 있어야 함
  if not (
    v_target_id = new.parent_comment_id
    or v_target_parent_id = new.parent_comment_id
  ) then
    raise exception '같은 댓글 스레드 안에서만 답글을 달 수 있어.';
  end if;

  -- reply_to_nickname 자동 보정
  if nullif(btrim(coalesce(new.reply_to_nickname, '')), '') is null then
    new.reply_to_nickname := coalesce(v_target_author_nickname, '익명');
  end if;

  return new;
end;
$$;

drop trigger if exists trg_validate_post_comment_parent on public.post_comments;
