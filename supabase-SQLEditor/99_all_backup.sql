create or replace function public.get_post_detail(
  p_post_id bigint,
  p_secret_password text default null
)
returns table (
  id bigint,
  title text,
  excerpt text,
  body text,
  category text,
  tags text[],
  pinned boolean,
  views integer,
  media_items jsonb,
  author_id uuid,
  author_nickname text,
  created_at timestamptz,
  updated_at timestamptz,
  is_private boolean,
  is_unlocked boolean
)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_post public.posts%rowtype;
  v_is_owner boolean := false;
  v_password_ok boolean := false;
  v_is_unlocked boolean := false;
begin
  select *
    into v_post
  from public.posts
  where posts.id = p_post_id;

  if not found then
    return;
  end if;

  v_is_owner := auth.uid() is not null and auth.uid() = v_post.author_id;

  if coalesce(v_post.is_private, false) = false then
    v_is_unlocked := true;
  else
    if v_is_owner then
      v_is_unlocked := true;
    else
      v_password_ok :=
        p_secret_password is not null
        and v_post.secret_password_hash is not null
        and encode(
              extensions.digest(p_secret_password, 'sha256'),
              'hex'
            ) = v_post.secret_password_hash;

      v_is_unlocked := v_password_ok;
    end if;
  end if;

  return query
  select
    v_post.id,
    v_post.title,
    v_post.excerpt,
    case
      when v_is_unlocked then v_post.body
      else ''
    end as body,
    v_post.category,
    v_post.tags,
    v_post.pinned,
    v_post.views,
    case
      when v_is_unlocked then v_post.media_items
      else '[]'::jsonb
    end as media_items,
    v_post.author_id,
    v_post.author_nickname,
    v_post.created_at,
    v_post.updated_at,
    coalesce(v_post.is_private, false) as is_private,
    v_is_unlocked as is_unlocked;
end;
$$;

grant execute on function public.get_post_detail(bigint, text) to anon, authenticated;

