  v_recovery_question := nullif(trim(coalesce(new.raw_user_meta_data->>'recovery_question', '')), '');
  v_recovery_answer_hash := nullif(trim(coalesce(new.raw_user_meta_data->>'recovery_answer_hash', '')), '');

